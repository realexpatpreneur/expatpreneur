// What someone may type in place of the full name.
export const SHORT: Record<string, string> = {
  "UAE": "United Arab Emirates",
  "UK": "United Kingdom",
  "US": "United States",
  "USA": "United States",
};

// Accent-blind, case-blind comparison, so "Malaga" finds the city with
// the accent on it.
export const fold = (s: string) =>
  s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();

// A stored comma separated value back into the entries it names.
export function splitVals(
  value: string | string[] | null | undefined,
  options: readonly string[]
) {
  const items = Array.isArray(value)
    ? value
    : String(value ?? "").split(",").map((x) => x.trim());
  return items
    .filter(Boolean)
    .map((x) => SHORT[x] ?? x)
    .filter((x) => options.includes(x));
}
